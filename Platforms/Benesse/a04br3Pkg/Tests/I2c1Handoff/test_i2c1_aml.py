#!/usr/bin/env python3
"""Check generated AML matches its source and rejects an empty handoff."""
import pathlib
import re
import subprocess
import tempfile

root = pathlib.Path(__file__).resolve().parents[2]
source = root / 'Drivers/I2c1HandoffDxe/Mma8652.asl'
header = root / 'Drivers/I2c1HandoffDxe/Mma8652Aml.h'
with tempfile.TemporaryDirectory(prefix='a04-i2c1-acpi-') as d:
    prefix = pathlib.Path(d) / 'ssdt'
    subprocess.run(['iasl', '-p', str(prefix), str(source)], check=True, capture_output=True)
    aml = prefix.with_suffix('.aml').read_bytes()
    embedded = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-f]{2})', header.read_text()))
    assert aml == embedded
    assert sum(aml) & 255 == 0
    assert aml.count(bytes.fromhex('78563412')) == 1
    assert aml.count(bytes.fromhex('21436587')) == 1
    p = subprocess.run(['acpiexec', '-b', 'evaluate _SB.ACC0._STA', str(prefix.with_suffix('.aml'))],
                       check=True, text=True, capture_output=True)
    assert '[Integer] = 0000000000000000' in p.stdout
    # Add mock-only AML methods which program the interpreter's emulated
    # OperationRegions, exercising both success and an explicitly gated clock.
    instrumented = source.read_text().replace(
        '   Method (_STA,',
        '   Method (TSET,0) { Store (0x41303431,HSTS) Store (0x240,MODE) '
        'Store (One,IENS) Return (HSTA ()) }\n'
        '   Method (TNEG,0) { Store (0x10,CGST) Return (HSTA ()) }\n'
        '   Method (_STA,', 1)
    test_source = pathlib.Path(d) / 'instrumented.asl'
    test_source.write_text(instrumented)
    subprocess.run(['iasl', '-p', str(prefix), str(test_source)], check=True, capture_output=True)
    p = subprocess.run(['acpiexec', '-b',
                        'evaluate _SB.ACC0.TSET; evaluate _SB.ACC0.TNEG',
                        str(prefix.with_suffix('.aml'))],
                       check=True, text=True, capture_output=True)
    assert '[Integer] = 0000000000000001' in p.stdout
    assert '[Integer] = 0000000000000000' in p.stdout
print('I2C1 SSDT generated bytes and empty-handoff _STA verified')
