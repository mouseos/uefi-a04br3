#!/usr/bin/env python3
"""Compile the board SSDT with iasl; embed an immutable timing record template."""
from pathlib import Path
import argparse,subprocess,tempfile,struct
p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);p.add_argument('--iasl',default='iasl');a=p.parse_args()
here=Path(__file__).resolve().parent;a.output.parent.mkdir(parents=True,exist_ok=True)
with tempfile.TemporaryDirectory(prefix='panel-aml-',dir=a.output.parent) as tmp:
 prefix=Path(tmp)/'PanelTiming';subprocess.run([a.iasl,'-p',str(prefix),str(here/'PanelTiming.asl')],check=True)
 b=prefix.with_suffix('.aml').read_bytes()
marker=struct.pack('<16I',0x314d5444,1,64,*([0]*13))
assert b.count(marker)==1 and len(b)>=36 and sum(b)%256==0
offset=b.index(marker)
s='/* Generated by generate-aml.py using PanelTiming.asl; do not edit. */\n#define A04_PANEL_AML_RECORD_OFFSET '+str(offset)+'u\nstatic const UINT8 mPanelTimingSsdt[] = {\n'
s+=''.join(' '+','.join('0x%02x'%x for x in b[i:i+16])+',\n' for i in range(0,len(b),16));s+='};\n';a.output.write_text(s)
